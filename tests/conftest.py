def request(proxy: MITM, method: str, url: str, body=None, headers=None, context=None):
    """
    Sends a request through the proxy (blocking).

    Returns:
        A tuple containing the status and body of the response.
    """
    scheme, rest = url.split("://", 1)
    authority, path = rest.split("/", 1)

    # HTTPS requests open a tunnel with 'CONNECT' first.
    if scheme == "https":
        connection = http.client.HTTPSConnection(HOST, proxy.port, timeout=TIMEOUT, context=context)
        connection.set_tunnel(authority)
        target = "/" + path

    # HTTP requests are sent with the full URL.
    else:
        connection = http.client.HTTPConnection(HOST, proxy.port, timeout=TIMEOUT)
        target = url

    try:
        connection.request(method, target, body=body, headers=headers if headers else {})
        response = connection.getresponse()
        return response.status, response.read()
    finally:
        connection.close()
