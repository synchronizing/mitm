HOST = "127.0.0.1"
TIMEOUT = 10


class Handler(http.server.BaseHTTPRequestHandler):
    """
    Request handler of the local server.
    """

    protocol_version = "HTTP/1.1"

    def log_message(self, *args):
        pass

    def send(self, status, body=b"", content_type="text/plain", headers=()):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        for name, value in headers:
            self.send_header(name, value)
        self.end_headers()

        # Responses to 'HEAD' requests do not have a body.
        if self.command != "HEAD":
            self.wfile.write(body)

    def do_HEAD(self):
        self.do_GET()

    def do_GET(self):
        if self.path == "/hello":
            self.send(200, b"hello")

        elif self.path == "/gzip":
            self.send(200, gzip.compress(b'{"compressed": true}'), "application/json", [("Content-Encoding", "gzip")])

        elif self.path == "/binary":
            self.send(200, b"\x89PNG\r\n\x1a\n\x00\x00", "image/png")

        elif self.path == "/chunked":
            self.send_response(200)
            self.send_header("Transfer-Encoding", "chunked")
            self.end_headers()
            for chunk in (b"first ", b"second"):
                self.wfile.write(b"%x\r\n%s\r\n" % (len(chunk), chunk))
            self.wfile.write(b"0\r\n\r\n")

        # Response without a 'Content-Length', which ends when the connection closes.
        elif self.path == "/close":
            self.send_response(200)
            self.send_header("Connection", "close")
            self.end_headers()
            self.wfile.write(b"until close")
            self.close_connection = True

        else:
            self.send(404, b"not found")

    def do_POST(self):
        body = self.rfile.read(int(self.headers["Content-Length"]))
        self.send(200, body, self.headers["Content-Type"])


class Server:
    """
    Local HTTP (or HTTPS) server, running in a separate thread.

    Args:
        context: SSL context of the server. Defaults to HTTP.
    """

    def __init__(self, context: Optional[ssl.SSLContext] = None):
        self.server = http.server.ThreadingHTTPServer((HOST, 0), Handler)
        self.server.daemon_threads = True
        if context:
            self.server.socket = context.wrap_socket(self.server.socket, server_side=True)
        self.port = self.server.server_address[1]
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    def close(self):
        self.server.shutdown()
        self.server.server_close()


